-- -----------------------------------------------------------------------------
-- nexus_reconfig_top.vhd
--
-- NexusReconfig reference design: force a reconfiguration of a Certus-NX FPGA
-- from internal logic by writing the LSC_REFRESH command to the configuration
-- block through the CONFIG_LMMI primitive.
--
-- Target: LFD2NX-40-8BG196C on the CRUVI Certus-NX board.
--
-- Clocking follows FPGA-TN-02099-3.7 Appendix D.2 (Figure D.2): the OSC IP's
-- hf_clk_out_o is the system clock and the LMMI clock source; the CONFIG_LMMI
-- LMMICLK and LMMIRESETN pins must be driven from the OSC IP's lmmi_clk_o and
-- lmmi_resetn_o pass-through outputs. RSTSMCLK and SMCLK are hardware inferred
-- and left unconnected, as in FPGA-RD-02294.
-- -----------------------------------------------------------------------------
library ieee;
use ieee.std_logic_1164.all;

entity nexus_reconfig_top is
    generic (
        AUTO_REFRESH_MS : natural := 10_000;    -- 0 = button only
        LED_ACTIVE_LOW  : boolean := false
    );
    port (
        btn_ni : in  std_logic;                     -- reconfiguration request button, active low
        led_o  : out std_logic_vector(1 downto 0);  -- (0) fresh-configuration indicator, (1) heartbeat
        txd_o  : out std_logic                      -- UART 115200 8N1
    );
end entity nexus_reconfig_top;

architecture rtl of nexus_reconfig_top is

    constant SYS_CLK_HZ : positive := 25_000_000;   -- osc0: 450 MHz / 18

    -- Oscillator IP generated by IP Catalog (lscc/osc0, Verilog).
    component osc0 is
        port (
            hf_out_en_i   : in  std_logic;
            lmmi_clk_i    : in  std_logic;
            lmmi_resetn_i : in  std_logic;
            hf_clk_out_o  : out std_logic;
            smclk_rst_o   : out std_logic;
            lmmi_clk_o    : out std_logic;
            lmmi_resetn_o : out std_logic
        );
    end component osc0;

    -- Nexus configuration-block LMMI primitive. Declaration as in the Radiant
    -- library cae_library/synthesis/vhdl/lfd2nx.vhd (package lfd2nx.components).
    component CONFIG_LMMI is
        generic (
            LMMI_EN : string := "DIS"
        );
        port (
            LMMICLK        : in  std_logic := 'X';
            LMMIREQUEST    : in  std_logic := 'X';
            LMMIWRRD_N     : in  std_logic := 'X';
            LMMIOFFSET     : in  std_logic_vector(7 downto 0);
            LMMIWDATA      : in  std_logic_vector(7 downto 0);
            LMMIRESETN     : in  std_logic := 'X';
            RSTSMCLK       : in  std_logic := 'X';
            SMCLK          : in  std_logic := 'X';
            LMMIRDATA      : out std_logic_vector(7 downto 0);
            LMMIREADY      : out std_logic;
            LMMIRDATAVALID : out std_logic
        );
    end component CONFIG_LMMI;

    attribute syn_noprune : boolean;

    signal sys_clk          : std_logic;
    signal rst_n            : std_logic;
    signal lmmi_clk         : std_logic;
    signal lmmi_resetn      : std_logic;
    signal lmmi_request     : std_logic;
    signal lmmi_wr_rdn      : std_logic;
    signal lmmi_ready       : std_logic;
    signal lmmi_rdata_valid : std_logic;
    signal lmmi_offset      : std_logic_vector(7 downto 0);
    signal lmmi_wdata       : std_logic_vector(7 downto 0);
    signal lmmi_rdata       : std_logic_vector(7 downto 0);

    attribute syn_noprune of config_lmmi_inst : label is true;

begin

    osc0_inst : osc0
        port map (
            hf_out_en_i   => '1',
            lmmi_clk_i    => sys_clk,
            lmmi_resetn_i => rst_n,
            hf_clk_out_o  => sys_clk,
            smclk_rst_o   => open,
            lmmi_clk_o    => lmmi_clk,
            lmmi_resetn_o => lmmi_resetn
        );

    u_core : entity work.reconfig_core
        generic map (
            CLK_HZ          => SYS_CLK_HZ,
            BAUD            => 115_200,
            AUTO_REFRESH_MS => AUTO_REFRESH_MS,
            LED_ACTIVE_LOW  => LED_ACTIVE_LOW
        )
        port map (
            clk_i          => sys_clk,
            rst_no         => rst_n,
            btn_ni         => btn_ni,
            led_o          => led_o,
            txd_o          => txd_o,
            lmmi_request_o => lmmi_request,
            lmmi_wr_rdn_o  => lmmi_wr_rdn,
            lmmi_offset_o  => lmmi_offset,
            lmmi_wdata_o   => lmmi_wdata,
            lmmi_ready_i   => lmmi_ready,
            refresh_done_o => open
        );

    config_lmmi_inst : CONFIG_LMMI
        generic map (
            LMMI_EN => "EN"
        )
        port map (
            LMMICLK        => lmmi_clk,
            LMMIREQUEST    => lmmi_request,
            LMMIWRRD_N     => lmmi_wr_rdn,
            LMMIOFFSET     => lmmi_offset,
            LMMIWDATA      => lmmi_wdata,
            LMMIRESETN     => lmmi_resetn,
            RSTSMCLK       => open,             -- hardware inferred
            SMCLK          => open,             -- hardware inferred
            LMMIRDATA      => lmmi_rdata,
            LMMIREADY      => lmmi_ready,
            LMMIRDATAVALID => lmmi_rdata_valid
        );

end architecture rtl;
